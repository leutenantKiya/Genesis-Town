// Writes docs/sim-report-30d.md: the brief's economy sanity check (30 game days, 50 simulated players).
//   node server/scripts/sim-report.ts [days=30] [players=50] [seed=42]
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { runSim } from '../src/game/sim.ts';
import { loadEcon } from '../src/game/econ.ts';

const [days, players, seed] = [Number(process.argv[2] ?? 30), Number(process.argv[3] ?? 50), Number(process.argv[4] ?? 42)];
const econ = loadEcon();
const t0 = Date.now();
const r = await runSim({ days, players, seed, econ });
const ms = Date.now() - t0;
const s = r.summary as { moneyStart: number; moneyEnd: number; moneyMax: number; moneyCap: number; priceRange: Record<string, { min: number; max: number; base: number }>; bankruptcies: number; recoveries: number; settlements: number };
const lo = econ.pricing.minMult, hi = econ.pricing.maxMult;
const pricesOk = Object.entries(s.priceRange).every(([, p]) => p.min >= lo * p.base - 1e-9 && p.max <= hi * p.base + 1e-9 && p.min > 0 && Number.isFinite(p.max));
const checks = [
  ['Money supply stays below the cap', s.moneyMax <= s.moneyCap, `max ${s.moneyMax} vs cap ${s.moneyCap}`],
  [`No price hits 0 or infinity (all within ${lo}-${hi} x base)`, pricesOk, 'see the price table'],
  ['At least one merchant goes bankrupt', s.bankruptcies >= 1, `${s.bankruptcies} closures`],
  ['...and recovers under investment', s.recoveries >= 1, `${s.recoveries} reopenings after restoration pledges`],
] as const;
const daily = r.frames.filter((_, i) => i % 24 === 23);
const name = (t: string) => econ.items[t]?.name ?? t;
const md = `# Economy simulation report: ${days} days, ${players} players

Generated by \`node server/scripts/sim-report.ts ${days} ${players} ${seed}\` on ${new Date().toISOString().slice(0, 10)} (run time ${(ms / 1000).toFixed(1)} s).

**What runs:** the real game code: \`server/src/game\` (world actions, merchants priced by \`economy/pricing.ts\`, town demand,
rent and storage fees, daily settlement), on an in-memory database and a mock chain that applies the same rules as the
contract. Simulated players fish, mine, chop wood, farm and cook; they eat when tired, buy tools, sell at the best bid twice
a day, use the shipping box when nobody buys, and pledge coin and goods to closed shops' restoration boards (producers
hold back goods those boards still need). Off-chain by design; deterministic for a seed.

## Acceptance checks

| Check | Result | Detail |
| --- | --- | --- |
${checks.map(([c, ok, d]) => `| ${c} | ${ok ? 'PASS' : 'FAIL'} | ${d} |`).join('\n')}

## Money supply

Start ${s.moneyStart}, end ${s.moneyEnd}, max ${s.moneyMax}, cap ${s.moneyCap} (Mcap0 x k with k = 1 + players/${econ.town.activePlayerDivisor}, at most ${econ.town.maxK}).

| Day | ${daily.map((f) => f.day).join(' | ')} |
| --- | ${daily.map(() => '---').join(' | ')} |
| Coin | ${daily.map((f) => f.moneySupply).join(' | ')} |

## Prices (average mid across merchants)

| Item | Base | Min | Max | End |
| --- | --- | --- | --- | --- |
${Object.entries(s.priceRange).map(([t, p]) => `| ${name(t)} | ${p.base} | ${p.min} | ${p.max} | ${r.frames[r.frames.length - 1].prices[t]} |`).join('\n')}

## Merchant cash at the end of each day

| Day | ${daily.map((f) => f.day).join(' | ')} |
| --- | ${daily.map(() => '---').join(' | ')} |
${Object.keys(econ.merchants).map((id) => `| ${econ.merchants[id].name} (${econ.merchants[id].personality}) | ${daily.map((f) => (f.merchants[id].open ? f.merchants[id].cash : `${f.merchants[id].cash} TUTUP`)).join(' | ')} |`).join('\n')}

## Events

${r.events.filter((e) => e.kind !== 'settled').map((e) => `- Day ${e.day}: ${e.text}`).join('\n') || '- none'}

## What the simulator taught us (changes made before this report)

- **Wood is gathered by hand.** With wood needing a tool and tools needing wood, the first runs deadlocked once wood ran out.
- **Joko is the "generous" merchant** (never bids under 90% of base, buys up to 3x target a day) with a smaller start
  (350 coin). A fair merchant lowers bids when short of cash and so never fails; the generous one overbuys.
- **Storage (gudang) fees**: 0.5 coin per unit above target stock per day, paid with rent and burned. Without them a
  hoarding merchant never ran out of cash, because the town buys stock overnight.
`;
const out = join(dirname(fileURLToPath(import.meta.url)), '../../docs/sim-report-30d.md');
writeFileSync(out, md);
console.log(checks.map(([c, ok]) => `${ok ? 'PASS' : 'FAIL'} ${c}`).join('\n'));
console.log('wrote', out);
if (!checks.every(([, ok]) => ok)) process.exitCode = 1;
